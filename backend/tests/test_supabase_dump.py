@pytest.fixture
def source_database():
    database_url = os.environ.get("TEST_POSTGRES_URL")
    if not database_url:
        pytest.skip("Set TEST_POSTGRES_URL to an expendable PostgreSQL admin database")
    psycopg = pytest.importorskip("psycopg")
    from psycopg import sql
    from psycopg.conninfo import make_conninfo
    from psycopg.rows import dict_row

    database_name = f"sa_dump_test_{uuid4().hex[:16]}"
    with psycopg.connect(database_url, autocommit=True) as admin:
        admin.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(database_name)))
    test_url = make_conninfo(database_url, dbname=database_name)
    try:
        with psycopg.connect(test_url, row_factory=dict_row) as connection:
            _create_source_schema(connection)
            _seed_source(connection)
        yield psycopg, test_url
    finally:
        with psycopg.connect(database_url, autocommit=True) as admin:
            admin.execute(
                sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(database_name))
            )


