def test_existing_output_is_never_overwritten(tmp_path):
    output = tmp_path / "existing"
    output.mkdir()
    marker = output / "keep.txt"
    marker.write_text("unchanged")
    with pytest.raises(ValueError, match="already exists"):
        export_bundle(None, output)
    assert marker.read_text() == "unchanged"


def _source_state(psycopg, database_url):
    from psycopg.rows import dict_row

    with psycopg.connect(database_url, row_factory=dict_row) as connection:
        counts = {
            table: connection.execute(f"SELECT count(*) AS n FROM {schema}.{table}").fetchone()["n"]
            for schema, table in (
                ("auth", "users"),
                ("public", "cohorts"),
                ("public", "invite_codes"),
                ("public", "members"),
                ("public", "profiles"),
                ("public", "posts"),
                ("public", "replies"),
                ("public", "post_votes"),
                ("public", "reply_votes"),
                ("public", "feedback"),
                ("storage", "objects"),
            )
        }
        sequences = {
            table: connection.execute(
                "SELECT last_value FROM "
                + connection.execute(
                    "SELECT pg_get_serial_sequence(%s, 'id') AS name", (f"public.{table}",)
                ).fetchone()["name"]
            ).fetchone()["last_value"]
            for table in ("posts", "replies", "feedback")
        }
        return {"counts": counts, "sequences": sequences}


def test_exported_snapshot_imports_and_verifies_through_services(source_database, db, tmp_path):
    """Use both real databases and the runtime migration services with a fresh namespace."""
    from app.database import bootstrap_indexes
    from app.forum.service import ForumService
    from app.migration import import_bundle, verify_bundle
    from app.profile.service import ProfileService

    psycopg, source_url = source_database
    output = tmp_path / "end-to-end"
    source_user = "00000000-0000-4000-8000-000000000001"
    client = httpx.Client(
        transport=httpx.MockTransport(lambda request: httpx.Response(200, content=b"avatar"))
    )
    try:
        with psycopg.connect(
            source_url, row_factory=__import__("psycopg.rows", fromlist=["dict_row"]).dict_row
        ) as source:
            export_bundle(source, output, supabase_url="https://project.example.test", http_client=client)
    finally:
        client.close()
    bundle = load_bundle(output)
    target = db.client[f"sa_mig_{uuid4().hex[:20]}"]
    try:
        planned = import_bundle(target, bundle)
        assert planned["applied"] is False
        assert target.list_collection_names() == []
        assert import_bundle(target, bundle, apply=True)["applied"] is True
        assert verify_bundle(target, bundle)["ok"]
        bootstrap_indexes(target)
        assert verify_bundle(target, bundle)["ok"]  # Startup must not add/delete source cohort records.
        svc = ForumService(target, {"id": source_user})
        profiles = ProfileService(target, {"id": source_user})
        post = svc.get_post(7)
        assert post["is_mine"] is True and post["upvote_count"] == 1
        assert profiles.get_own_profile()["role_verified"] is True
        assert target.members.find_one({"user_id": source_user})["is_admin"] is True
        assert target.feedback.find_one({"id": 4})["user_id"].endswith("000000000002")
        svc.create_post({"title": "New after import", "body": "Next id", "is_anonymous": True})
        assert target.posts.find_one({"title": "New after import"})["id"] == 91
        with pytest.raises(MigrationError, match="completed snapshot differs"):
            import_bundle(target, bundle, apply=True)
    finally:
        db.client.drop_database(target.name)


def test_unused_identity_sequences_keep_first_id_available(source_database, tmp_path):
    psycopg, source_url = source_database
    with psycopg.connect(source_url) as source:
        source.execute(
            "TRUNCATE auth.users, public.cohorts, public.invite_codes, public.members, "
            "public.profiles, public.posts, public.replies, public.post_votes, "
            "public.reply_votes, public.feedback, storage.objects RESTART IDENTITY CASCADE"
        )
    with psycopg.connect(
        source_url, row_factory=__import__("psycopg.rows", fromlist=["dict_row"]).dict_row
    ) as source:
        manifest = export_bundle(source, tmp_path / "empty-source")
    assert manifest["sequences"] == {"post": 0, "reply": 0, "feedback": 0}
    assert all(item["count"] == 0 for item in manifest["tables"].values())
