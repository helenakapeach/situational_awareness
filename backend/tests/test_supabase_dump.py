class ReadOnlySpy:
    """Connection proxy that records PostgreSQL's active read-only setting."""

    def __init__(self, connection):
        self.connection = connection
        self.read_only_during_export = None

    def __getattr__(self, name):
        return getattr(self.connection, name)

    def execute(self, statement, parameters=None):
        result = (
            self.connection.execute(statement, parameters)
            if parameters is not None
            else self.connection.execute(statement)
        )
        if str(statement).startswith("SET TRANSACTION ISOLATION LEVEL"):
            self.read_only_during_export = self.connection.execute("SHOW transaction_read_only").fetchone()[
                "transaction_read_only"
            ]
        return result


